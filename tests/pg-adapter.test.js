const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('crypto');
const pg = require('pg');
const { compile, bind } = require('../lib/pg/sql');
const { createDatabase, isConstraintError, TransactionClosedError } = require('../lib/pg');

const adminUrl = process.env.PG_TEST_URL;

test('placeholders: ? and named parameters become $n; literals, identifiers, comments and casts are left alone', () => {
  const a = compile(`SELECT '?' AS q, "we?ird" FROM t WHERE a = ? AND b LIKE '%?%' -- ? here\n AND c = ? /* ? */ AND d::text = ?`);
  assert.equal(a.text, `SELECT '?' AS q, "we?ird" FROM t WHERE a = $1 AND b LIKE '%?%' -- ? here\n AND c = $2 /* ? */ AND d::text = $3`);
  assert.equal(a.positional, 3);
  const b = compile('INSERT INTO r (fw, ref, note) VALUES (@fw, :ref, $fw) ON CONFLICT DO NOTHING');
  assert.equal(b.text, 'INSERT INTO r (fw, ref, note) VALUES ($1, $2, $1) ON CONFLICT DO NOTHING');
  assert.deepEqual(bind(b, [{ fw: 7, ref: 'x' }]), [7, 'x']);
  assert.equal(compile(`SELECT $tag$ ? @x $tag$, ?`).text, 'SELECT $tag$ ? @x $tag$, $1');
  assert.equal(compile("SELECT 'it''s ?', ?").text, "SELECT 'it''s ?', $1");
  assert.deepEqual(bind(compile('SELECT ?, ?, ?'), [[1, 2], true]), [1, 2, 1]);
  assert.deepEqual(bind(compile('SELECT ?'), [undefined]), [null], 'undefined binds as NULL, as with better-sqlite3');
  assert.throws(() => bind(compile('SELECT ?, ?'), [1]), /Expected 2/);
  assert.throws(() => bind(compile('SELECT @a'), [{}]), /Missing named parameter "a"/);
});

test('a database: typed results, new-row ids, transactions and their binding', { skip: !adminUrl && 'PG_TEST_URL is not set' }, async (t) => {
  const name = `adapter_${crypto.randomBytes(4).toString('hex')}`;
  const admin = new pg.Client({ connectionString: adminUrl });
  await admin.connect();
  await admin.query(`CREATE DATABASE ${name} TEMPLATE template0 LC_COLLATE 'C' LC_CTYPE 'C' ENCODING 'UTF8'`);
  const url = new URL(adminUrl); url.pathname = `/${name}`;
  const db = createDatabase(url.toString(), { max: 4 });
  t.after(async () => {
    await db.close();
    await admin.query(`DROP DATABASE IF EXISTS ${name} WITH (FORCE)`);
    await admin.end();
  });

  await db.exec(`
    CREATE TABLE items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text UNIQUE NOT NULL, n bigint DEFAULT 0, price numeric);
    CREATE TABLE tags (item_id bigint NOT NULL, tag text NOT NULL, PRIMARY KEY (item_id, tag));`);
  await db.loadCatalog();

  const first = await db.prepare('INSERT INTO items (name, n, price) VALUES (?, ?, ?)').run('alpha', 3, '1.50');
  assert.deepEqual(first, { changes: 1, lastInsertRowid: 1 });
  const skipped = await db.prepare('INSERT INTO items (name) VALUES (?) ON CONFLICT (name) DO NOTHING').run('alpha');
  assert.deepEqual(skipped, { changes: 0, lastInsertRowid: undefined }, 'a skipped insert never reports an id');
  const noId = await db.prepare('INSERT INTO tags (item_id, tag) VALUES (?, ?)').run(1, 'x');
  assert.deepEqual(noId, { changes: 1, lastInsertRowid: undefined });

  const counts = await db.prepare('SELECT COUNT(*) AS c, SUM(n) AS s, MAX(price) AS p FROM items').get();
  assert.deepEqual(counts, { c: 1, s: 3, p: 1.5 }, 'counts and sums are numbers, not strings');
  assert.equal(await db.prepare('SELECT * FROM items WHERE id = ?').get(99), undefined);
  assert.equal((await db.prepare("SELECT current_setting('TimeZone') AS tz").get()).tz, 'UTC');
  assert.deepEqual(await db.prepare('SELECT id, name FROM items').raw().all(), [[1, 'alpha']]);

  const add = db.transaction(async (label) => {
    await db.prepare('INSERT INTO items (name) VALUES (?)').run(label);
    if (label === 'fail') throw new Error('rolled back');
    return label;
  });
  assert.equal(await add('beta'), 'beta');
  await assert.rejects(add('fail'), /rolled back/);
  assert.equal((await db.prepare("SELECT COUNT(*) c FROM items WHERE name = 'fail'").get()).c, 0);

  const outer = db.transaction(async () => {
    await db.prepare('INSERT INTO items (name) VALUES (?)').run('gamma');
    await assert.rejects(db.transaction(async () => {
      await db.prepare('INSERT INTO items (name) VALUES (?)').run('delta');
      throw new Error('inner fails');
    })(), /inner fails/);
    assert.equal(db.inTransaction, true);
    return (await db.prepare("SELECT COUNT(*) c FROM items WHERE name IN ('gamma','delta')").get()).c;
  });
  assert.equal(await outer(), 1, 'a failed nested transaction rolls back only its savepoint');
  assert.equal(db.inTransaction, false);

  let lateQuery;
  await db.transaction(async () => {
    lateQuery = new Promise(resolve => setTimeout(() => db.prepare('SELECT 1').get().then(() => resolve(null), resolve), 30));
  })();
  assert.ok((await lateQuery) instanceof TransactionClosedError);

  const error = await db.prepare('INSERT INTO items (name) VALUES (?)').run('alpha').catch(e => e);
  assert.ok(isConstraintError(error), 'unique violations are recognised as constraint errors');

  const warnings = [];
  const onWarning = (warning) => warnings.push(warning.message);
  process.on('warning', onWarning);
  const together = await db.transaction(async () => {
    await Promise.all(['p1', 'p2', 'p3', 'p4'].map((label) => db.prepare('INSERT INTO items (name) VALUES (?)').run(label)));
    const results = await Promise.all(['s1', 's2', 'fail', 's3'].map((label) => db.transaction(async () => {
      await db.prepare('INSERT INTO items (name) VALUES (?)').run(label);
      if (label === 'fail') throw new Error('one nested transaction fails');
      return label;
    })().catch((error) => error.message)));
    return { results, rows: (await db.prepare("SELECT name FROM items WHERE name IN ('p1','p2','p3','p4','s1','s2','s3','fail') ORDER BY name").all()).map((row) => row.name) };
  })();
  await new Promise((resolve) => setImmediate(resolve));
  process.off('warning', onWarning);
  assert.deepEqual(together.results, ['s1', 's2', 'one nested transaction fails', 's3']);
  assert.deepEqual(together.rows, ['p1', 'p2', 'p3', 'p4', 's1', 's2', 's3'], 'only the failed savepoint is rolled back');
  assert.deepEqual(warnings.filter((message) => /already executing a query/.test(message)), []);

  const started = [];
  const settle = () => new Promise((resolve) => setTimeout(resolve, 20));
  await db.transaction(async () => {
    db.afterCommit(() => started.push(`kept:${db.inTransaction}`));
    await db.transaction(async () => { db.afterCommit(() => started.push('savepoint rolled back')); throw new Error('undo'); })().catch(() => {});
    await db.transaction(async () => { db.afterCommit(() => started.push('savepoint kept')); })();
    assert.deepEqual(started, [], 'nothing starts before COMMIT');
  })();
  await db.transaction(async () => { db.afterCommit(() => started.push('rolled back')); throw new Error('undo'); })().catch(() => {});
  db.afterCommit(() => started.push('outside a transaction'));
  await settle();
  assert.deepEqual(started, ['kept:false', 'savepoint kept', 'outside a transaction']);

  let order = [];
  const slow = db.transaction(async (tag, ms) => {
    order.push(`${tag}:start`);
    await new Promise(resolve => setTimeout(resolve, ms));
    order.push(`${tag}:end`);
  });
  const later = (run) => new Promise(resolve => setTimeout(resolve, 20)).then(run);
  await Promise.all([slow('a', 120), later(() => slow('b', 1))]);
  assert.deepEqual(order, ['a:start', 'a:end', 'b:start', 'b:end']);
  order = [];
  await Promise.all([slow.immediate('a', 120), later(() => slow('b', 1))]);
  assert.deepEqual(order, ['a:start', 'a:end', 'b:start', 'b:end']);
  order = [];
  await Promise.all([slow('a', 120), later(() => slow.concurrent('b', 1))]);
  assert.deepEqual(order, ['a:start', 'b:start', 'b:end', 'a:end']);
});

test('a transaction waiting too long for the writer lock fails instead of hanging', { skip: !adminUrl && 'PG_TEST_URL is not set' }, async (t) => {
  const name = `adapter_${crypto.randomBytes(4).toString('hex')}`;
  const admin = new pg.Client({ connectionString: adminUrl });
  await admin.connect();
  await admin.query(`CREATE DATABASE ${name} TEMPLATE template0 LC_COLLATE 'C' LC_CTYPE 'C' ENCODING 'UTF8'`);
  const url = new URL(adminUrl); url.pathname = `/${name}`;
  const db = createDatabase(url.toString(), { max: 4, lockTimeoutMs: 100 });
  t.after(async () => {
    await db.close();
    await admin.query(`DROP DATABASE IF EXISTS ${name} WITH (FORCE)`);
    await admin.end();
  });
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  const escaped = gate.then(() => db.transaction(async () => 'never')().then(() => null, e => e));
  await db.transaction(async () => {
    release();
    const error = await escaped;
    assert.equal(error && error.code, '55P03', 'lock_timeout ends the wait with lock_not_available');
  })();
});
